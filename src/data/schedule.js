// helpers
export const todayIndex = () => (new Date().getDay() + 6) % 7
export const nowHours = () => { const d = new Date(); return d.getHours() + d.getMinutes() / 60 + d.getSeconds() / 3600 }
export const fmt = v => { let H = Math.floor(v), M = Math.round((v - H) * 60); if (M === 60) { H++; M = 0 } return String(H).padStart(2, '0') + ':' + String(M).padStart(2, '0') }
export const dur = m => { m = Math.round(m); const h = Math.floor(m / 60), mm = m % 60; return ((h ? h + ' год ' : '') + (mm ? mm + ' хв' : '')).trim() }
export const itemsForDay = d => ALL_ITEMS.filter(p => p.d.includes(d))
export const programAt = (d, h) => PROGRAMS.find(p => p.d.includes(d) && h >= p.a && h < p.b)
export const itemKey = (d, p) => `${d}-${p.a}-${p.t}`
